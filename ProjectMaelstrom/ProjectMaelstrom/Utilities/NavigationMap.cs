using System.Buffers.Binary;

namespace ProjectMaelstrom.Utilities;

internal readonly record struct NavigationPoint(double X, double Y, double Z);
internal readonly record struct NavigationEdge(int From, int To);
internal sealed record NavigationPath(bool Found, string Reason, IReadOnlyList<int> Vertices, double Distance, int Visited);

/// <summary>Immutable structural zone graph. A graph path does not establish physical clearance,
/// a safe connector from the player, or permission to send movement.</summary>
internal sealed class NavigationMap
{
    public const int MaximumVertices = 32767;
    public const int MaximumEdges = 250000;
    public const int MaximumBytes = 6 + MaximumVertices * 14 + 4 + MaximumEdges * 4;
    public IReadOnlyList<NavigationPoint> Points { get; }
    public IReadOnlyList<NavigationEdge> Edges { get; }
    public short HeaderCount { get; }
    public short HeaderUnknown { get; }
    public int VertexRecords { get; }
    public int SkippedVertexRecords => VertexRecords - Points.Count;
    public string Sha256 { get; private set; } = "";
    private readonly int[][] outgoing;

    private NavigationMap(short headerCount, short headerUnknown, int vertexRecords,
        NavigationPoint[] points, NavigationEdge[] edges)
    {
        HeaderCount = headerCount;
        HeaderUnknown = headerUnknown;
        VertexRecords = vertexRecords;
        Points = Array.AsReadOnly(points);
        Edges = Array.AsReadOnly(edges);
        var lists = Enumerable.Range(0, points.Length).Select(_ => new List<int>()).ToArray();
        foreach (var edge in edges) lists[edge.From].Add(edge.To);
        outgoing = lists.Select(list => list.ToArray()).ToArray();
    }

