    /// <summary>Read little-endian zone.nav only, rejecting trailing bytes. The first and third
    /// header fields are preserved, not interpreted as a format version or portal table.</summary>
    public static NavigationMap Parse(byte[] data)
    {
        ArgumentNullException.ThrowIfNull(data);
        if (data.Length < 10 || data.Length > MaximumBytes) throw new InvalidDataException("Navigation byte budget exceeded or header truncated.");
        int offset = 0;
        short ReadShort()
        {
            if (data.Length - offset < 2) throw new InvalidDataException("Truncated navigation integer.");
            short value = BinaryPrimitives.ReadInt16LittleEndian(data.AsSpan(offset, 2));
            offset += 2;
            return value;
        }
        float ReadFloat()
        {
            if (data.Length - offset < 4) throw new InvalidDataException("Truncated navigation coordinate.");
            float value = BitConverter.Int32BitsToSingle(BinaryPrimitives.ReadInt32LittleEndian(data.AsSpan(offset, 4)));
            offset += 4;
            if (!float.IsFinite(value)) throw new InvalidDataException("Nonfinite navigation coordinate.");
            return value;
        }
        short count = ReadShort(), records = ReadShort(), unknown = ReadShort();
        if (count < 0 || records <= 0 || count > records || data.Length - offset < records * 14 + 4)
            throw new InvalidDataException("Invalid navigation record count.");
        var points = new List<NavigationPoint>(records);
        for (int record = 0; record < records; record++)
        {
            var point = new NavigationPoint(ReadFloat(), ReadFloat(), ReadFloat());
            short index = ReadShort();
            if (index < 0 || index >= records) throw new InvalidDataException("Invalid navigation vertex index.");
            // Equivalent to the legacy loop's decrement of remaining records on an index gap.
            if (index == points.Count) points.Add(point);
        }
        if (points.Count == 0) throw new InvalidDataException("Navigation contains no indexed vertices.");
        int edgeCount = BinaryPrimitives.ReadInt32LittleEndian(data.AsSpan(offset, 4));
        offset += 4;
        if (edgeCount < 0 || edgeCount > MaximumEdges || data.Length - offset != edgeCount * 4)
            throw new InvalidDataException("Invalid navigation edge count or trailing bytes.");
        var edges = new NavigationEdge[edgeCount];
        for (int edge = 0; edge < edgeCount; edge++)
        {
            int from = ReadShort(), to = ReadShort();
            if (from < 0 || to < 0 || from >= points.Count || to >= points.Count)
                throw new InvalidDataException("Navigation edge refers to a missing vertex.");
            edges[edge] = new(from, to);
        }
        return new(count, unknown, records, points.ToArray(), edges)
        { Sha256 = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(data)).ToLowerInvariant() };
    }

    /// <summary>Bounded Dijkstra search over directed edges and explicit vertex IDs. Blocked
    /// edges apply in one direction only. No implicit player-to-vertex connector is added.</summary>
    public NavigationPath FindPath(int start, int goal, IReadOnlySet<NavigationEdge>? blocked = null, int maximumVisited = 10000)
    {
        if (start < 0 || start >= Points.Count) throw new ArgumentOutOfRangeException(nameof(start));
        if (goal < 0 || goal >= Points.Count) throw new ArgumentOutOfRangeException(nameof(goal));
        if (maximumVisited < 1 || maximumVisited > MaximumVertices) throw new ArgumentOutOfRangeException(nameof(maximumVisited));
        var distances = Enumerable.Repeat(double.PositiveInfinity, Points.Count).ToArray();
        var parents = Enumerable.Repeat(-1, Points.Count).ToArray();
        var settled = new bool[Points.Count];
        var queue = new PriorityQueue<int, (double Distance, int Vertex)>();
        distances[start] = 0;
        queue.Enqueue(start, (0, start));
        int visited = 0;
        while (queue.TryDequeue(out int current, out _))
        {
            if (settled[current]) continue;
            if (visited == maximumVisited) return new(false, "visit-budget-exhausted", Array.Empty<int>(), 0, visited);
            settled[current] = true;
            visited++;
            if (current == goal)
            {
                var path = new List<int>();
                for (int node = goal; node != -1; node = parents[node]) path.Add(node);
                path.Reverse();
                return new(true, "graph-path", path.AsReadOnly(), distances[goal], visited);
            }
            foreach (int next in outgoing[current])
            {
                if (settled[next] || blocked?.Contains(new(current, next)) == true) continue;
                var a = Points[current];
                var b = Points[next];
                double dx = a.X - b.X, dy = a.Y - b.Y, dz = a.Z - b.Z;
                double candidate = distances[current] + Math.Sqrt(dx * dx + dy * dy + dz * dz);
                if (candidate >= distances[next]) continue;
                distances[next] = candidate;
                parents[next] = current;
                queue.Enqueue(next, (candidate, next));
            }
        }
        return new(false, "unreachable", Array.Empty<int>(), 0, visited);
    }
}
